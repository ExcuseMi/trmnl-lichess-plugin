// Generates source/pieces.js from assets/pieces/cburnett/Chess_*t45.svg (Colin M.L. Burnett, BSD, LICENSES/cburnett-BSD-3.txt):
// the inner markup of each 45 x 45 file, whitespace squeezed, styles as attributes, shapes untouched. Run after changing the SVGs; test/pieces.test.js checks it is current.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'assets/pieces/cburnett');
function inner(file) {
  const t = fs.readFileSync(path.join(DIR, file), 'utf8');
  const m = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(t);
  if (!m) throw new Error('no svg in ' + file);
  return noStyles(m[1].replace(/\s+id="[^"]*"/g, '')).replace(/\s+/g, ' ').replace(/> </g, '><').replace(/ >/g, '>').trim();
}
// style="..." becomes presentation attributes (the TRMNL lint refuses inline styles and opacity); defaults are left out.
// Also used by tools/build.js for the icon (a Cburnett knight).
const DEFAULTS = { opacity: '1', 'fill-opacity': '1', 'stroke-opacity': '1', 'stroke-miterlimit': '4', 'stroke-dasharray': 'none' };
const attrs = (css) => css.split(';').map((d) => d.split(':').map((s) => s.trim())).filter(([k, v]) => k && v && DEFAULTS[k] !== v).map(([k, v]) => k + '="' + v + '"').join(' ');
function noStyles(svg) { return svg.replace(/style="([^"]*)"/g, (_, css) => attrs(css)); }
function generate() {
  const out = {};
  for (const c of 'wb') for (const p of 'KQRBNP') out[c + p] = inner('Chess_' + p.toLowerCase() + (c === 'w' ? 'l' : 'd') + 't45.svg');
  return '// Generated by tools/pieces.js from assets/pieces/cburnett (Colin M.L. Burnett, BSD licence). Do not edit.\nvar PIECE_SVG = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n  "') + ';\n';
}
module.exports = { generate, noStyles };
if (require.main === module) { fs.writeFileSync(path.join(ROOT, 'source/pieces.js'), generate()); console.log('source/pieces.js'); }
